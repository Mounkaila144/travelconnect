        <h1>Politique de confidentialite</h1>
        <p class="date">Derniere mise a jour : 11 avril 2026</p>

        <p>TravelConnect (ci-apres "l'application") respecte la vie privee de ses utilisateurs et s'engage a proteger leurs donnees personnelles. Cette politique de confidentialite explique quelles informations nous collectons, comment nous les utilisons et quels sont vos droits.</p>

        <h2>1. Informations collectees</h2>

        <h3>1.1 Informations de compte</h3>
        <ul>
            <li>Adresse email (via Google Sign-In ou Apple Sign-In)</li>
            <li>Nom d'affichage</li>
            <li>Photo de profil (facultatif)</li>
        </ul>

        <h3>1.2 Donnees de localisation</h3>
        <ul>
            <li>Position approximative (pour la publication et l'affichage des questions)</li>
            <li>La localisation n'est collectee qu'avec votre autorisation</li>
        </ul>

        <h3>1.3 Contenu genere par l'utilisateur</h3>
        <ul>
            <li>Questions publiees</li>
            <li>Reponses publiees</li>
            <li>Evaluations</li>
        </ul>

        <h3>1.4 Donnees d'utilisation</h3>
        <ul>
            <li>Statistiques d'utilisation de l'application (via Firebase Analytics)</li>
            <li>Rapports de crash (via Firebase Crashlytics)</li>
            <li>Informations sur l'appareil (version du systeme d'exploitation, modele)</li>
        </ul>

        <h2>2. Utilisation des informations</h2>
        <p>Les informations collectees sont utilisees pour :</p>
        <ul>
            <li>Fournir les fonctionnalites de base (affichage des questions/reponses, carte)</li>
            <li>Envoyer des notifications push</li>
            <li>Calculer le score de confiance</li>
            <li>Moderer le contenu inapproprie</li>
            <li>Ameliorer l'application et corriger les bugs</li>
            <li>Fournir le support utilisateur</li>
        </ul>

        <h2>3. Services tiers</h2>
        <p>L'application utilise les services tiers suivants :</p>
        <ul>
            <li><strong>Google Sign-In :</strong> authentification</li>
            <li><strong>Apple Sign-In :</strong> authentification (iOS)</li>
            <li><strong>Google Maps :</strong> affichage de la carte et fonctionnalites de localisation</li>
            <li><strong>Firebase Cloud Messaging :</strong> notifications push</li>
            <li><strong>Firebase Analytics :</strong> analyse d'utilisation</li>
            <li><strong>Firebase Crashlytics :</strong> rapports de crash</li>
        </ul>
        <p>Veuillez consulter les politiques de confidentialite respectives de ces services sur leurs sites officiels.</p>

        <h2>4. Stockage et securite des donnees</h2>
        <ul>
            <li>Les donnees sont transmises via HTTPS (chiffrement)</li>
            <li>Les mots de passe sont haches avant stockage</li>
            <li>Le serveur dispose de mesures de securite appropriees</li>
            <li>Les droits d'acces sont limites au strict necessaire</li>
        </ul>

        <h2>5. Partage des donnees</h2>
        <p>L'application ne partage pas vos informations personnelles avec des tiers, sauf dans les cas suivants :</p>
        <ul>
            <li>Le contenu que vous choisissez de publier (questions, reponses)</li>
            <li>Les exigences legales de divulgation</li>
            <li>Le partage technique avec les services tiers mentionnes ci-dessus</li>
        </ul>

        <h2>6. Vos droits</h2>
        <p>Vous disposez des droits suivants :</p>
        <ul>
            <li><strong>Droit d'acces :</strong> demander l'acces a vos donnees personnelles</li>
            <li><strong>Droit de rectification :</strong> demander la correction de donnees inexactes</li>
            <li><strong>Droit de suppression :</strong> demander la suppression de vos donnees</li>
            <li><strong>Droit a la portabilite :</strong> demander l'export de vos donnees</li>
            <li><strong>Suppression de compte :</strong> supprimer votre compte depuis les parametres de l'application</li>
        </ul>

        <h2>7. Protection des mineurs</h2>
        <p>L'application ne s'adresse pas aux enfants de moins de 13 ans et ne collecte pas intentionnellement de donnees personnelles aupres d'enfants de moins de 13 ans.</p>

        <h2>8. Modifications de la politique</h2>
        <p>Cette politique de confidentialite peut etre mise a jour si necessaire. En cas de modification importante, les utilisateurs seront informes via l'application.</p>

        <h2>9. Contact</h2>
        <p>Pour toute question ou demande relative a la confidentialite :</p>
